#!/usr/bin/env bash
# ABNO DECK - installer for Debian 13 (trixie) and derivatives.
#
# Installs the app for the *current user* (no system-wide Python changes, the
# app itself is never run as root). sudo is used only for optional system
# pieces: apt packages, the udev permission rule and (optionally) nothing else.
#
# Usage:
#   ./install.sh                 # deps + files + .desktop + login autostart
#   ./install.sh --extras        # also install xdotool/playerctl/xdg-utils
#   ./install.sh --dialout       # add your user to the dialout group (serial access)
#   ./install.sh --udev          # install the uaccess udev rule (serial access)
#   ./install.sh --auto-launch   # start the GUI when the ESP32 is plugged in
#   ./install.sh --no-autostart  # do not start ABNO DECK at desktop login
#   ./install.sh --no-deps       # skip apt, assume dependencies are present
set -euo pipefail

SOURCE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_ROOT="${XDG_DATA_HOME:-$HOME/.local/share}/abno-deck"
TARGET="$APP_ROOT/app"
BIN_DIR="$HOME/.local/bin"
WRAPPER="$BIN_DIR/abno-deck"
DESKTOP_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
AUTOSTART_DIR="$HOME/.config/autostart"
ICON_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/icons/hicolor/scalable/apps"
USER_UNIT_DIR="$HOME/.config/systemd/user"
UDEV_RULE_SRC="$SOURCE_DIR/packaging/99-abno-deck.rules"
UDEV_RULE_DST="/etc/udev/rules.d/99-abno-deck.rules"

WITH_EXTRAS=0
WITH_DIALOUT=0
WITH_UDEV=0
WITH_AUTOLAUNCH=0
WITH_AUTOSTART=1
WITH_DEPS=1
PYTHON_BIN=""

log()  { printf '\033[1;36m[abno-deck]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[abno-deck] warning:\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m[abno-deck] error:\033[0m %s\n' "$*" >&2; exit 1; }

for arg in "$@"; do
  case "$arg" in
    --extras) WITH_EXTRAS=1 ;;
    --dialout) WITH_DIALOUT=1 ;;
    --udev) WITH_UDEV=1 ;;
    --auto-launch) WITH_AUTOLAUNCH=1; WITH_UDEV=1 ;;
    --no-autostart) WITH_AUTOSTART=0 ;;
    --no-deps) WITH_DEPS=0 ;;
    -h|--help) grep '^#' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown option: $arg (see --help)" ;;
  esac
done

SUDO=""
if [ "$(id -u)" -ne 0 ]; then
  command -v sudo >/dev/null 2>&1 || [ "$WITH_DEPS$WITH_UDEV$WITH_DIALOUT" = "000" ] || \
    die "sudo is required for apt/udev/dialout steps (or re-run with --no-deps and skip those flags)"
  SUDO="sudo"
fi

# ---------------------------------------------------------------- dependencies
have_runtime() {
  python3 -c "import PySide6, serial" >/dev/null 2>&1
}

install_dependencies() {
  if ! command -v python3 >/dev/null 2>&1; then
    die "python3 not found - install it first: sudo apt install python3"
  fi
  if have_runtime; then
    PYTHON_BIN="$(command -v python3)"
    log "Python dependencies already present (system python)"
    return
  fi
  if [ "$WITH_DEPS" -eq 1 ]; then
    log "installing Python dependencies from Debian packages (needs sudo)"
    $SUDO apt-get update || warn "apt-get update failed - continuing with cached indexes"
    $SUDO apt-get install -y python3 python3-pyserial \
      python3-pyside6.qtcore python3-pyside6.qtgui python3-pyside6.qtwidgets \
      || warn "apt could not provide PySide6 - falling back to a virtualenv (pip)"
  fi
  if have_runtime; then
    PYTHON_BIN="$(command -v python3)"
    log "using system Python: $PYTHON_BIN"
    return
  fi
  log "creating a virtualenv at $APP_ROOT/venv and installing PySide6 + pyserial"
  python3 -m venv "$APP_ROOT/venv" || die "python3-venv missing - run: sudo apt install python3-venv"
  "$APP_ROOT/venv/bin/pip" install --quiet --upgrade pip
  "$APP_ROOT/venv/bin/pip" install --quiet -r "$SOURCE_DIR/requirements.txt"
  PYTHON_BIN="$APP_ROOT/venv/bin/python3"
  have_runtime || die "dependencies could not be installed - check the output above"
}

if [ "$WITH_EXTRAS" -eq 1 ]; then
  log "installing optional helper tools (xdotool, playerctl, xdg-utils)"
  $SUDO apt-get install -y xdotool playerctl xdg-utils || warn "some optional tools failed to install"
fi

install_dependencies

# ---------------------------------------------------------------- app files
log "installing application files to $TARGET"
mkdir -p "$TARGET"
cp -R "$SOURCE_DIR/src" "$TARGET/"
cp "$SOURCE_DIR/main.py" "$SOURCE_DIR/requirements.txt" "$SOURCE_DIR/LICENSE" \
   "$SOURCE_DIR/sample-profile.json" "$TARGET/"
[ -d "$SOURCE_DIR/assets" ] && cp -R "$SOURCE_DIR/assets" "$TARGET/"
[ -d "$SOURCE_DIR/packaging" ] && cp -R "$SOURCE_DIR/packaging" "$TARGET/"
if [ -f "$SOURCE_DIR/README.md" ]; then cp "$SOURCE_DIR/README.md" "$TARGET/"; fi
find "$TARGET" -name '__pycache__' -type d -prune -exec rm -rf {} + 2>/dev/null || true
chmod +x "$TARGET/main.py"

log "creating launcher $WRAPPER"
mkdir -p "$BIN_DIR"
cat > "$WRAPPER" <<EOF
#!/usr/bin/env bash
# ABNO DECK launcher (generated by install.sh)
exec "$PYTHON_BIN" "$TARGET/main.py" "\$@"
EOF
chmod +x "$WRAPPER"

# ---------------------------------------------------------------- desktop entry
log "installing desktop entry and icon"
mkdir -p "$DESKTOP_DIR" "$ICON_DIR"
sed -e "s|__EXEC__|$WRAPPER|g" "$SOURCE_DIR/abno-deck.desktop" > "$DESKTOP_DIR/abno-deck.desktop"
[ -f "$SOURCE_DIR/assets/abno-deck.svg" ] && cp "$SOURCE_DIR/assets/abno-deck.svg" "$ICON_DIR/abno-deck.svg"
command -v update-desktop-database >/dev/null 2>&1 && update-desktop-database "$DESKTOP_DIR" >/dev/null 2>&1 || true

if [ "$WITH_AUTOSTART" -eq 1 ]; then
  log "enabling start at desktop login (~/.config/autostart)"
  mkdir -p "$AUTOSTART_DIR"
  cp "$DESKTOP_DIR/abno-deck.desktop" "$AUTOSTART_DIR/abno-deck.desktop"
fi

# ---------------------------------------------------------------- serial access
if [ "$WITH_DIALOUT" -eq 1 ]; then
  log "adding $USER to the dialout group (log out and back in for it to apply)"
  $SUDO usermod -aG dialout "$USER"
fi

if [ "$WITH_UDEV" -eq 1 ]; then
  log "installing udev permission rule (device access only - never launches a GUI)"
  $SUDO cp "$UDEV_RULE_SRC" "$UDEV_RULE_DST"
  $SUDO udevadm control --reload-rules 2>/dev/null || true
  $SUDO udevadm trigger --subsystem-match=tty 2>/dev/null || true
fi

# ---------------------------------------------------------------- auto-launch
if [ "$WITH_AUTOLAUNCH" -eq 1 ]; then
  log "installing opt-in USB auto-launch (systemd --user path unit)"
  mkdir -p "$USER_UNIT_DIR"
  cp "$SOURCE_DIR/packaging/abno-deck-watch.path" "$USER_UNIT_DIR/abno-deck-watch.path"
  sed -e "s|__WRAPPER__|$WRAPPER|g" "$SOURCE_DIR/packaging/abno-deck-watch.service" \
      > "$USER_UNIT_DIR/abno-deck-watch.service"
  if systemctl --user daemon-reload 2>/dev/null; then
    systemctl --user enable --now abno-deck-watch.path 2>/dev/null || \
      warn "could not enable abno-deck-watch.path (no active user session?)"
  else
    warn "systemctl --user is unavailable in this context - run after logging in:"
    warn "  systemctl --user daemon-reload && systemctl --user enable --now abno-deck-watch.path"
  fi
fi

# ---------------------------------------------------------------- summary
cat <<EOF

ABNO DECK installed.

  Launch:        $WRAPPER
                 or start "ABNO DECK" from the MATE menu
  Check env:     $WRAPPER --doctor
  Config:        ~/.config/abno-deck/
  Log:           ~/.config/abno-deck/abno-deck.log
EOF

if [ "$WITH_DIALOUT" -eq 1 ]; then
  echo "  Serial access: dialout group added - log out and back in, then plug the ESP32 in."
fi
if [ "$WITH_UDEV" -eq 1 ]; then
  echo "  Serial access: udev uaccess rule installed at $UDEV_RULE_DST"
fi
if [ "$WITH_AUTOLAUNCH" -eq 1 ]; then
  cat <<'EOF'
  Auto-launch:   ABNO DECK starts when a USB serial device is plugged in,
                 through a systemd --user path unit (runs as YOUR user, never
                 as root). Limitations: it only works while you are logged in,
                 it triggers on /dev/serial/by-id appearing (not on the
                 ABNODECK:READY message), and it uses a fixed DISPLAY=:0.
                 Disable with: systemctl --user disable --now abno-deck-watch.path
EOF
fi
if [ "$WITH_EXTRAS" -eq 0 ]; then
  echo "  Note:         keyboard shortcuts need xdotool (X11) or wtype (Wayland),"
  echo "                media control needs playerctl. Re-run with --extras to get them."
fi
echo
echo "Uninstall with: ./uninstall.sh (add --purge to also remove the configuration)"
